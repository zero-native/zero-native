android {
    namespace = "dev.zeronative.sample"
    compileSdk = 37
    ndkVersion = "30.0.16248370"

    defaultConfig {
        applicationId = "dev.zeronative.sample"
        minSdk = 24
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"

        ndk {
            abiFilters += listOf("arm64-v8a")
        }
    }

    buildTypes {
        // Debug also packs x86_64, so the sample runs on an emulator. Release stays arm64-only: size numbers are for phones.
