// Writes compiler/src/tag-props.ts: which props each zero-native element takes, read from the element types in
// packages/ui/src/index.ts (RN-compat sweep P0.8, 2026-11-05). The compiler uses it to fail the build on a prop the
// element doesn't take (`<Image horizontal>`, `<Text value>`): before, such a prop was accepted and did nothing.
// The types are the one list: a prop added to an element's type is accepted by the compiler after this runs.
// Run: bun run gen:tag-props. compiler/test/tag-props.test.ts fails if the file is out of date.
import { join } from "node:path"
import ts from "typescript"
import { Component } from "../packages/template/src/registry"

export const UI_TYPES_PATH = join(import.meta.dir, "../packages/ui/src/index.ts")
export const TAG_PROPS_PATH = join(import.meta.dir, "../compiler/src/tag-props.ts")

/** The names of a type's properties; for a union (an element with two shapes), of every member. */
function propNames(checker: ts.TypeChecker, type: ts.Type): string[] {
  const names = new Set<string>()
  for (const t of type.isUnion() ? type.types : [type]) {
    for (const p of checker.getPropertiesOfType(t)) names.add(p.name)
  }
  return [...names].sort()
}

export function tagPropsFile(): string {
  const program = ts.createProgram([UI_TYPES_PATH], {
    strict: true,
    noEmit: true,
    skipLibCheck: true,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    types: [],
  })
  const checker = program.getTypeChecker()
  const sf = program.getSourceFile(UI_TYPES_PATH)
  if (!sf) throw new Error(`can't read ${UI_TYPES_PATH}`)
  const moduleSymbol = checker.getSymbolAtLocation(sf)!

  const tags: Record<string, string[]> = {}
  for (const exp of checker.getExportsOfModule(moduleSymbol)) {
    if (!(exp.name in Component)) continue // only elements of the registry (not View, FlatList: the compiler renames those)
    const type = checker.getTypeOfSymbolAtLocation(exp, sf)
    const param = type.getCallSignatures()[0]?.getParameters()[0]
    if (!param) continue
    tags[exp.name] = propNames(checker, checker.getTypeOfSymbolAtLocation(param, sf))
  }
  const declared = (name: string) => {
    // An exported interface through the module's exports (its scope symbol is the export, with no members).
    const sym = checker.getExportsOfModule(moduleSymbol).find((s) => s.name === name) ??
      checker.getSymbolsInScope(sf, ts.SymbolFlags.Interface).find((s) => s.name === name)
    if (!sym) throw new Error(`interface ${name} not found in ${UI_TYPES_PATH}`)
    return propNames(checker, checker.getDeclaredTypeOfSymbol(sym))
  }
  const style = [...new Set([...declared("StyleProps"), ...declared("TextStyleProps")])].sort()
  if (style.length < 50) throw new Error(`only ${style.length} style keys found: the type reading is broken`)
  const base = declared("Base")

  const list = (names: readonly string[]) => names.map((n) => JSON.stringify(n)).join(", ")
  const lines = [
    "// GENERATED by tools/gen-tag-props.ts from packages/ui/src/index.ts. Do not edit: change the element's type there,",
    "// then run `bun run gen:tag-props`.",
    "",
    "/** The keys a `style` may hold (StyleProps and TextStyleProps). */",
    `export const STYLE_KEYS: ReadonlySet<string> = new Set([${list(style)}])`,
    "",
    "/** The props every element has (Base), left out of the hint that lists an element's own props. */",
    `export const BASE_PROPS: ReadonlySet<string> = new Set([${list(base)}])`,
    "",
    "/**",
    " * Each element's props and events, as its type in @zeronative/ui says: `base` = it has every BASE_PROPS prop too,",
    " * `own` = the rest. An element not listed isn't checked.",
    " */",
    "export const TAG_PROPS: Readonly<Record<string, { base: boolean; own: ReadonlySet<string> }>> = {",
    ...Object.keys(tags).sort().map((t) => {
      const hasBase = base.every((p) => tags[t].includes(p))
      const own = hasBase ? tags[t].filter((p) => !base.includes(p)) : tags[t]
      return `  ${t}: { base: ${hasBase}, own: new Set([${list(own)}]) },`
    }),
    "}",
    "",
  ]
  return lines.join("\n")
}

if (import.meta.main) {
  await Bun.write(TAG_PROPS_PATH, tagPropsFile())
  console.log(`wrote ${TAG_PROPS_PATH}`)
}
