// Writes the Kotlin and Swift copies of the component registry from packages/template/src/registry.ts, and the registry lock
// (packages/template/registry.lock.json) after checking the change follows the OTA rules (registry-lock.ts).
// Run: bun run gen:registry. packages/template/test/registry.test.ts fails if the Kotlin file or the lock is out of date.
import { join } from "node:path"
import { existsSync, readFileSync } from "node:fs"
import { Component, DynamicProps, Enum, EventKind, Prop, REGISTRY_VERSION } from "../packages/template/src/registry"
import { registryProblems, registrySnapshot, type RegistryLock } from "../packages/template/src/registry-lock"

export const KOTLIN_REGISTRY_PATH = join(
  import.meta.dir,
  "../android/runtime/src/main/java/dev/zeronative/runtime/Registry.kt",
)
export const REGISTRY_LOCK_PATH = join(import.meta.dir, "../packages/template/registry.lock.json")

const constName = (s: string) =>
  s
    .replace(/-/g, "_")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toUpperCase()

const ints = (values: number[]) => `intArrayOf(${values.join(", ")})`
/** Prop value types as numbers for Kotlin (TemplateReader checks each value against its prop's type). */
const PROP_TYPE_CODES = ["number", "size", "string", "color", "enum", "bool"]

export function kotlinRegistry(): string {
  const lines: string[] = []
  lines.push("// GENERATED by tools/gen-registry.ts from packages/template/src/registry.ts. Do not edit.")
  lines.push("package dev.zeronative.runtime")
  lines.push("")
  lines.push("/** Component, prop, event and enum ids used in .zn.ui templates (ARCHITECTURE.md §6.1). */")
  lines.push("object Registry {")
  lines.push(`    const val VERSION = ${REGISTRY_VERSION}`)
  lines.push("")
  lines.push("    object Component {")
  for (const [name, id] of Object.entries(Component)) lines.push(`        const val ${constName(name)} = ${id}`)
  lines.push("    }")
  lines.push("")
  lines.push("    object Prop {")
  for (const [name, p] of Object.entries(Prop)) lines.push(`        const val ${constName(name)} = ${p.id}`)
  lines.push("    }")
  lines.push("")
  lines.push("    object Event {")
  for (const [name, id] of Object.entries(EventKind)) lines.push(`        const val ${constName(name)} = ${id}`)
  lines.push("    }")
  for (const [prop, values] of Object.entries(Enum)) {
    lines.push("")
    lines.push(`    object ${prop[0].toUpperCase()}${prop.slice(1)} {`)
    for (const [name, v] of Object.entries(values)) lines.push(`        const val ${constName(name)} = ${v}`)
    lines.push("    }")
  }
  lines.push("")
  lines.push("    /** Every id this app knows: templates from an OTA bundle that use any other id are refused (TemplateReader). */")
  lines.push(`    val COMPONENT_IDS = ${ints(Object.values(Component))}`)
  lines.push(`    val PROP_IDS = ${ints(Object.values(Prop).map((p) => p.id))}`)
  lines.push("    /** The value type of each prop in PROP_IDS (same order): 0 number, 1 size, 2 string, 3 color, 4 enum, 5 bool. */")
  lines.push(`    val PROP_TYPES = ${ints(Object.values(Prop).map((p) => PROP_TYPE_CODES.indexOf(p.type)))}`)
  lines.push(`    val DYNAMIC_PROP_IDS = ${ints([...DynamicProps].map((p) => Prop[p].id))}`)
  lines.push(`    val EVENT_IDS = ${ints(Object.values(EventKind))}`)
  lines.push("    /** Enum prop id → the values this app knows. */")
  lines.push("    val ENUM_VALUES = mapOf(")
  for (const [prop, values] of Object.entries(Enum)) {
    lines.push(`        ${Prop[prop as keyof typeof Prop].id} to ${ints(Object.values(values))},`)
  }
  lines.push("    )")
  lines.push("}")
  lines.push("")
  return lines.join("\n")
}

export const SWIFT_REGISTRY_PATH = join(import.meta.dir, "../ios/ZnRuntime/Swift/Registry.swift")

const SWIFT_KEYWORDS = new Set([
  "default", "static", "public", "private", "in", "is", "as", "case", "class", "struct", "enum", "func", "var", "let",
  "return", "switch", "where", "while", "for", "if", "else", "repeat", "self", "Self", "super", "true", "false", "nil",
  "import", "init", "inout", "internal", "operator", "protocol", "subscript", "throw", "throws", "try", "Type",
])
/** "space-between" → spaceBetween, "Column" → column; Swift keywords in backticks. */
const swiftName = (s: string) => {
  const camel = s.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase())
  const name = camel[0].toLowerCase() + camel.slice(1)
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name
}
const swiftType = (s: string) => s[0].toUpperCase() + s.slice(1)

/** The Swift copy of the registry, for the iOS renderer (same ids as Registry.kt). */
export function swiftRegistry(): string {
  const lines: string[] = []
  lines.push("// GENERATED by tools/gen-registry.ts from packages/template/src/registry.ts. Do not edit.")
  lines.push("")
  lines.push("/// Component, prop, event and enum ids used in .zn.ui templates (ARCHITECTURE.md §6.1).")
  lines.push("enum Registry {")
  lines.push(`    static let version = ${REGISTRY_VERSION}`)
  lines.push("")
  lines.push("    enum Component {")
  for (const [name, id] of Object.entries(Component)) lines.push(`        static let ${swiftName(name)}: Int = ${id}`)
  lines.push("    }")
  lines.push("")
  lines.push("    enum Prop {")
  for (const [name, p] of Object.entries(Prop)) lines.push(`        static let ${swiftName(name)}: Int = ${p.id}`)
  lines.push("    }")
  lines.push("")
  lines.push("    enum Event {")
  for (const [name, id] of Object.entries(EventKind)) lines.push(`        static let ${swiftName(name)}: Int = ${id}`)
  lines.push("    }")
  for (const [prop, values] of Object.entries(Enum)) {
    lines.push("")
    lines.push(`    enum ${swiftType(prop)} {`)
    for (const [name, v] of Object.entries(values)) lines.push(`        static let ${swiftName(name)}: Int = ${v}`)
    lines.push("    }")
  }
  lines.push("")
  lines.push("    /// Every id this app knows: templates from an OTA bundle that use any other id are refused (TemplateReader).")
  lines.push(`    static let componentIds: Set<Int> = [${Object.values(Component).join(", ")}]`)
  lines.push(`    static let propIds: [Int] = [${Object.values(Prop).map((p) => p.id).join(", ")}]`)
  lines.push("    /// The value type of each prop in propIds (same order): 0 number, 1 size, 2 string, 3 color, 4 enum, 5 bool.")
  lines.push(`    static let propTypes: [Int] = [${Object.values(Prop).map((p) => PROP_TYPE_CODES.indexOf(p.type)).join(", ")}]`)
  lines.push(`    static let dynamicPropIds: Set<Int> = [${[...DynamicProps].map((p) => Prop[p].id).join(", ")}]`)
  lines.push(`    static let eventIds: Set<Int> = [${Object.values(EventKind).join(", ")}]`)
  lines.push("    /// Enum prop id → the values this app knows.")
  lines.push("    static let enumValues: [Int: Set<Int>] = [")
  for (const [prop, values] of Object.entries(Enum)) {
    lines.push(`        ${Prop[prop as keyof typeof Prop].id}: [${Object.values(values).join(", ")}],`)
  }
  lines.push("    ]")
  lines.push("}")
  lines.push("")
  return lines.join("\n")
}

/** The lock file's text for the current registry: one line per entry, so a change shows as a one-line diff. */
export function registryLockText(): string {
  const lock = registrySnapshot()
  const entries = Object.entries(lock.entries).map(([key, e]) => `    ${JSON.stringify(key)}: ${JSON.stringify(e)}`)
  return `{\n  "version": ${lock.version},\n  "base": ${lock.base},\n  "entries": {\n${entries.join(",\n")}\n  }\n}\n`
}

export function readRegistryLock(): RegistryLock | null {
  return existsSync(REGISTRY_LOCK_PATH) ? (JSON.parse(readFileSync(REGISTRY_LOCK_PATH, "utf8")) as RegistryLock) : null
}

if (import.meta.main) {
  const lock = readRegistryLock()
  const problems = lock ? registryProblems(lock) : []
  if (problems.length > 0) {
    console.error("registry change not allowed (nothing written):\n- " + problems.join("\n- "))
    process.exit(1)
  }
  await Bun.write(KOTLIN_REGISTRY_PATH, kotlinRegistry())
  console.log("wrote", KOTLIN_REGISTRY_PATH)
  await Bun.write(SWIFT_REGISTRY_PATH, swiftRegistry())
  console.log("wrote", SWIFT_REGISTRY_PATH)
  await Bun.write(REGISTRY_LOCK_PATH, registryLockText())
  console.log("wrote", REGISTRY_LOCK_PATH)
}
