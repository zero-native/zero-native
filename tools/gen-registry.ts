// Writes the Kotlin copy of the component registry from packages/template/src/registry.ts.
// Run: bun run gen:registry. packages/template/test/registry.test.ts fails if the Kotlin file is out of date.
import { join } from "node:path"
import { Component, Enum, EventKind, Prop, REGISTRY_VERSION } from "../packages/template/src/registry"

export const KOTLIN_REGISTRY_PATH = join(
  import.meta.dir,
  "../android/runtime/src/main/java/dev/zeronative/runtime/Registry.kt",
)

const constName = (s: string) =>
  s
    .replace(/-/g, "_")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toUpperCase()

export function kotlinRegistry(): string {
  const lines: string[] = []
  lines.push("// GENERATED by tools/gen-registry.ts from packages/template/src/registry.ts. Do not edit.")
  lines.push("package dev.zeronative.runtime")
  lines.push("")
  lines.push("/** Component, prop, event and enum ids used in .zn.ui templates (ARCHITECTURE.md §6.1). */")
  lines.push("object Registry {")
  lines.push(`    const val VERSION = ${REGISTRY_VERSION}`)
  lines.push("")
  lines.push("    object Component {")
  for (const [name, id] of Object.entries(Component)) lines.push(`        const val ${constName(name)} = ${id}`)
  lines.push("    }")
  lines.push("")
  lines.push("    object Prop {")
  for (const [name, p] of Object.entries(Prop)) lines.push(`        const val ${constName(name)} = ${p.id}`)
  lines.push("    }")
  lines.push("")
  lines.push("    object Event {")
  for (const [name, id] of Object.entries(EventKind)) lines.push(`        const val ${constName(name)} = ${id}`)
  lines.push("    }")
  for (const [prop, values] of Object.entries(Enum)) {
    lines.push("")
    lines.push(`    object ${prop[0].toUpperCase()}${prop.slice(1)} {`)
    for (const [name, v] of Object.entries(values)) lines.push(`        const val ${constName(name)} = ${v}`)
    lines.push("    }")
  }
  lines.push("}")
  lines.push("")
  return lines.join("\n")
}

if (import.meta.main) {
  await Bun.write(KOTLIN_REGISTRY_PATH, kotlinRegistry())
  console.log("wrote", KOTLIN_REGISTRY_PATH)
}
